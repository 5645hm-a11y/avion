"""Stage the public repository (https://github.com/5645hm-a11y/avion) after build_site.py and render_cards.py.
  python tools/release/stage_pages.py

Since 9 November 2026 AVION is open source (AGPLv3 or a commercial licence, LICENSING.md), and the repository has two branches:
- main: the source. It holds an allowlist of the working tree (below), staged into build/public-source/.
- gh-pages: the site that GitHub Pages serves at https://5645hm-a11y.github.io/avion/. It holds docs/site (pages, fonts, logos,
  showcase pictures, the reel, the bundle, the packages and the licences) and .nojekyll, staged into build/gh-pages-dist/.

Each staging directory is its own git checkout of that branch; the script keeps their .git and replaces everything else. It
refuses to stage a binary or build output, any file over 50 MB (GitHub refuses 100 MB), or a media file that is not one of the
self-generated fixtures listed here. A local .release-private.json (never published) may name more files to refuse and the
patterns written to the public checkout's .git/info/exclude.
"""
import json, pathlib, shutil, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SITE = ROOT / "docs" / "site"
PAGES = ROOT / "build" / "gh-pages-dist"
SOURCE = ROOT / "build" / "public-source"
SITE_URL = "https://5645hm-a11y.github.io/avion/"
REPO_URL = "https://github.com/5645hm-a11y/avion"

# main: what is published, relative to the working tree.
TOP_FILES = ["README.md", "LICENSE", "LICENSING.md", "CONTRIBUTING.md", "CMakeLists.txt"]
TREES = ["src", "include", "apps", "tests", "tools", "docs", "samples"]
SKIP_DIRS = {"__pycache__", "bin", "obj", ".vs"}  # docs/site (the gh-pages branch) is left out below.
# Self-generated test fixtures (tools/realworld/make_mkv_fixtures.py and make_compat_matrix.py: ffmpeg's testsrc2 and sine).
FIXTURES = [f"assets/test_fixtures/mkv/{n}" for n in (
    "av1_aac.mkv", "av1_opus.webm", "av1_opus_live.webm", "chapters.txt", "cues.ass", "cues.srt", "h264_aac_ass.mkv",
    "h264_aac_srt_chapters.mkv", "h264_opus.mkv", "hevc10_aac.mkv", "hevc_aac.mkv")] + [
    f"assets/test_fixtures/compat/{n}" for n in ("h264_aac_two_audio.mkv", "vp9_opus.webm", "x264_high_default.mp4", "x264_start_offset.mp4", "stts_last_zero.mp4")]
BANNED_SUFFIXES = {".exe", ".dll", ".pdb", ".lib", ".obj", ".o", ".pyc", ".ilk", ".exp", ".idb", ".zip", ".whl", ".nupkg"}
PRIVATE = ROOT / ".release-private.json"  # Local only (see the docstring).
LOCAL = json.loads(PRIVATE.read_text(encoding="utf-8")) if PRIVATE.exists() else {}
BANNED_NAMES = set(LOCAL.get("never_publish", []))
MEDIA_SUFFIXES = {".mp4", ".mkv", ".webm", ".mov", ".m4a", ".wav", ".raw", ".yuv", ".h264", ".hevc", ".265"}
GITIGNORE = """# Build outputs and local tools.
/build/
/.vs/
__pycache__/
*.pyc
samples/csharp/AvionPlayer/bin/
samples/csharp/AvionPlayer/obj/
# Large or third-party media: generated or fetched by the scripts under tools/ (see README.md, "Test fixtures").
/assets/test_fixtures/*.mp4
/assets/test_fixtures/mkv/h264_bframes_720p_10m.mkv
/assets/test_fixtures/mkv/av_sync_clock_45m.mkv
/assets/test_fixtures/mkv/big_buck_bunny_4k60.mkv
/assets/real_world/
"""


def clear(dist):
    dist.mkdir(parents=True, exist_ok=True)
    for p in dist.iterdir():  # Keep .git: the branch's history lives there.
        if p.name != ".git":
            shutil.rmtree(p) if p.is_dir() else p.unlink()


def files_of(dist):
    return [p for p in dist.rglob("*") if p.is_file() and ".git" not in p.relative_to(dist).parts]


def stage_site():
    clear(PAGES)
    for p in SITE.rglob("*"):
        if p.is_file():
            dst = PAGES / p.relative_to(SITE)
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(p, dst)
    (PAGES / ".nojekyll").write_text("", encoding="utf-8")
    (PAGES / "README.md").write_text(
        f"# AVION site\n\nThe `gh-pages` branch: the pages GitHub Pages serves at {SITE_URL}, generated by `tools/site/build_site.py` "
        f"and staged by `tools/release/stage_pages.py`. The source is on the [`main` branch]({REPO_URL}).\n", encoding="utf-8", newline="\n")
    code = [p for p in files_of(PAGES) if p.suffix.lower() in {".c", ".cpp", ".h", ".hpp", ".py", ".cmake"}]
    if code:
        sys.exit("refusing to stage source into the site branch: " + ", ".join(str(p.relative_to(PAGES)) for p in code))


def stage_source():
    clear(SOURCE)
    chosen = [ROOT / n for n in TOP_FILES]
    for tree in TREES:
        for p in (ROOT / tree).rglob("*"):
            rel = p.relative_to(ROOT)
            if p.is_file() and not (SKIP_DIRS & set(rel.parts[1:-1]) or (tree == "docs" and rel.parts[1:2] == ("site",))):
                chosen.append(p)
    chosen += [ROOT / f for f in FIXTURES]
    problems = []
    for p in chosen:
        rel = p.relative_to(ROOT)
        if not p.exists(): problems.append(f"missing {rel}"); continue
        if p.suffix.lower() in BANNED_SUFFIXES or p.name in BANNED_NAMES: problems.append(f"banned {rel}")
        if p.stat().st_size > 50_000_000: problems.append(f"too large {rel}")
        if p.suffix.lower() in MEDIA_SUFFIXES and rel.as_posix() not in FIXTURES: problems.append(f"unlisted media {rel}")
    if problems:
        sys.exit("refusing to stage the source: " + "; ".join(problems))
    for p in chosen:
        dst = SOURCE / p.relative_to(ROOT)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(p, dst)
    (SOURCE / ".gitignore").write_text(GITIGNORE, encoding="utf-8", newline="\n")
    if (SOURCE / ".git" / "info").is_dir() and LOCAL.get("git_exclude"):  # Ignored locally, never listed in the public .gitignore.
        (SOURCE / ".git" / "info" / "exclude").write_text("\n".join(LOCAL["git_exclude"]) + "\n", encoding="utf-8", newline="\n")


stage_site()
stage_source()
for name, dist in (("gh-pages", PAGES), ("main", SOURCE)):
    files = files_of(dist)
    print(f"{name}: staged {len(files)} files, {sum(p.stat().st_size for p in files):,} bytes in {dist}")
